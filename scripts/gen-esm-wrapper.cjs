#!/usr/bin/env node
/**
 * `scripts/gen-esm-wrapper.cjs`
 * - generate the ESM entry points that re-export the CJS build (v5 B1).
 * - one implementation (CJS `dist/**`), two entries: `require` gets `dist/index.js`,
 *   `import` gets `dist/esm/index.mjs`, which reads the same CJS `module.exports`.
 * - the value names (value, value+type) come from the TypeScript compiler API over the
 *   built `.d.ts` (same method as `scripts/api-names.cjs`). type-only names are skipped.
 * - output is deterministic: names sorted, no date or path in the file.
 *
 * | output                  | from                            | CJS target                    |
 * | ----------------------- | ------------------------------- | ----------------------------- |
 * | `dist/esm/index.mjs`    | `dist/index.d.ts`               | `../index.js`                 |
 * | `dist/esm/testing.mjs`  | `dist/common/test-helper.d.ts`  | `../common/test-helper.js`    |
 * | `dist/esm/model.mjs`    | `dist/model.d.ts`               | `../model.js`                 |
 *
 * usage:
 * ```sh
 * $ npm run build                              # runs this script at the end
 * $ node scripts/gen-esm-wrapper.cjs           # (re)write dist/esm/*.mjs
 * $ node scripts/gen-esm-wrapper.cjs --check   # render twice, compare with each other and dist/esm (exit 1 on diff)
 * ```
 */
const fs = require('fs');
const path = require('path');
const ts = require('typescript');

// package root (one level above `scripts/`).
const root = path.resolve(__dirname, '..');

// wrapper files to generate: output, source `.d.ts`, and the CJS file each re-exports.
const TARGETS = [
    { out: 'dist/esm/index.mjs', dts: 'dist/index.d.ts', cjs: '../index.js' },
    { out: 'dist/esm/testing.mjs', dts: 'dist/common/test-helper.d.ts', cjs: '../common/test-helper.js' },
    //* v5 B16: `lemon-core/model` = every value of lemon-model (sub-path, the root stays at the 32 v4 names).
    { out: 'dist/esm/model.mjs', dts: 'dist/model.d.ts', cjs: '../model.js' },
];

// sort by code unit, so the order does not depend on the locale.
const byCode = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * read the value names (value, value+type) exported by a `.d.ts` file.
 * @returns sorted names, `default` included when present.
 */
const readValueNames = dtsFile => {
    const program = ts.createProgram([dtsFile], { declaration: true, noEmit: true, skipLibCheck: true });
    const checker = program.getTypeChecker();
    const source = program.getSourceFile(dtsFile);
    const moduleSymbol = source && checker.getSymbolAtLocation(source);
    if (!moduleSymbol) throw new Error(`no module symbol for ${path.relative(root, dtsFile)}`);
    // true if the export (or the symbol it aliases) is a runtime value.
    const isValue = sym => {
        const target = sym.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(sym) : sym;
        return (target.flags & ts.SymbolFlags.Value) !== 0;
    };
    return checker
        .getExportsOfModule(moduleSymbol)
        .filter(isValue)
        .map(sym => sym.getName())
        .sort(byCode);
};

/**
 * render one wrapper file.
 * @param names     value names (sorted), may include `default`.
 * @param cjsPath   import specifier of the CJS file, relative to `dist/esm/`.
 * @param from      `.d.ts` path for the header (relative to the package root).
 */
const render = (names, cjsPath, from) => {
    const named = names.filter(n => n !== 'default');
    const lines = [
        `// generated by scripts/gen-esm-wrapper.cjs from ${from}. do not edit.`,
        `import cjs from '${cjsPath}';`,
        ...named.map(n => `export const ${n} = cjs.${n};`),
    ];
    if (names.includes('default')) lines.push(`export default cjs.default;`);
    return lines.join('\n') + '\n';
};

// render every target from its `.d.ts` (throws if the build is missing).
const build = () =>
    TARGETS.map(t => {
        const dts = path.join(root, t.dts);
        if (!fs.existsSync(dts)) throw new Error(`not found: ${t.dts} (run \`npm run build-ts\` first)`);
        const names = readValueNames(dts);
        return { ...t, names, text: render(names, t.cjs, t.dts) };
    });

// write the wrappers, or with `--check` compare two renders and the files on disk; returns the exit code.
const main = () => {
    const check = process.argv.slice(2).includes('--check');
    const first = build();
    // write mode: write each wrapper and print its name count.
    if (!check) {
        first.forEach(r => {
            const file = path.join(root, r.out);
            fs.mkdirSync(path.dirname(file), { recursive: true });
            fs.writeFileSync(file, r.text);
            const named = r.names.filter(n => n !== 'default').length;
            const def = r.names.includes('default') ? ' + default' : '';
            console.log(`gen-esm-wrapper: ${r.out} <- ${r.dts}: ${named} named${def}`);
        });
        return 0;
    }
    // check mode: render again and compare with the first render and the file on disk.
    const second = build();
    let bad = 0;
    first.forEach((r, i) => {
        const file = path.join(root, r.out);
        const disk = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
        const same2 = r.text === second[i].text;
        const sameDisk = r.text === disk;
        if (!same2 || !sameDisk) bad++;
        const onDisk = sameDisk ? 'same' : disk === null ? 'MISSING' : 'DIFF';
        console.log(`gen-esm-wrapper --check: ${r.out} render-twice=${same2 ? 'same' : 'DIFF'} disk=${onDisk}`);
    });
    return bad ? 1 : 0;
};

// run as a CLI only (the module can also be required for its helpers).
if (require.main === module) {
    try {
        process.exit(main());
    } catch (e) {
        console.error(`! gen-esm-wrapper: ${e.message}`);
        process.exit(1);
    }
}

module.exports = { readValueNames, render, TARGETS };
